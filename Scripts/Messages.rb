def csvField!(str)
  ret = ""
  str.sub!(/\A\s*/, "")
  if str[0, 1] == "\""
    str[0, 1] = ""
    escaped = false
    fieldbytes = 0
    str.scan(/./) do |s|
      fieldbytes += s.length
      break if s == "\"" && !escaped

      if s == "\\" && !escaped
        escaped = true
      else
        ret += s
        escaped = false
      end
    end
    str[0, fieldbytes] = ""
    if !str[/\A\s*,/] && !str[/\A\s*$/]
      raise _INTL("Invalid quoted field (in: {1})", ret)
    end

    str[0, str.length] = $~.post_match
  else
    if str[/,/]
      str[0, str.length] = $~.post_match
      ret = $~.pre_match
    else
      ret = str.clone
      str[0, str.length] = ""
    end
    ret.gsub!(/\s+$/, "")
  end
  return ret
end

def csvPosInt!(str)
  ret = csvField!(str)
  if !ret[/\A\d+$/]
    raise _INTL("Field {1} is not a positive integer", ret)
  end

  return ret.to_i
end

class ChooseNumberParams
  def initialize
    @maxDigits = 0
    @minNumber = 0
    @maxNumber = 0
    @skin = nil
    @messageSkin = nil
    @negativesAllowed = false
    @autoClamp = false
    @initialNumber = 0
    @cancelNumber = nil
  end

  def setMessageSkin(value)
    @messageSkin = value
  end

  def messageSkin # Set the full path for the message's window skin
    @messageSkin
  end

  def setSkin(value)
    @skin = value
  end

  def skin
    @skin
  end

  def setNegativesAllowed(value)
    @negativeAllowed = value
  end

  def negativesAllowed
    @negativeAllowed ? true : false
  end

  def setRange(minNumber, maxNumber)
    maxNumber = minNumber if minNumber > maxNumber
    @maxDigits = 0
    @minNumber = minNumber
    @maxNumber = maxNumber
  end

  def setDefaultValue(number)
    @initialNumber = number
    @cancelNumber = nil
  end

  def setInitialValue(number)
    @initialNumber = number
  end

  def setCancelValue(number)
    @cancelNumber = number
  end

  def initialNumber
    return clamp(@initialNumber, self.minNumber, self.maxNumber)
  end

  def cancelNumber
    return @cancelNumber ? @cancelNumber : self.initialNumber
  end

  def minNumber
    ret = 0
    if @maxDigits > 0
      ret = -((10**@maxDigits) - 1)
    else
      ret = @minNumber
    end
    ret = 0 if !@negativeAllowed && ret < 0
    return ret
  end

  def maxNumber
    ret = 0
    if @maxDigits > 0
      ret = ((10**@maxDigits) - 1)
    else
      ret = @maxNumber
    end
    ret = 0 if !@negativeAllowed && ret < 0
    return ret
  end

  def setMaxDigits(value)
    @maxDigits = [1, value].max
  end

  def maxDigits
    if @maxDigits > 0
      return @maxDigits
    else
      return [numDigits(self.minNumber), numDigits(self.maxNumber)].max
    end
  end

  def setAutoClamp(value) # Rather than treating max and min values as bounds, clamp entered numbers to them
    @autoClamp = value
  end

  def autoClamp(number)
    return number unless @autoClamp
    return clamp(number, self.minNumber, self.maxNumber)
  end

  private

  def clamp(v, mn, mx)
    v = v.to_i
    mn = mn.to_i
    mx = mx.to_i
    return v < mn ? mn : (v > mx ? mx : v)
  end

  def numDigits(number)
    ans = 1
    number = number.abs
    while number >= 10
      ans += 1
      number /= 10
    end
    return ans
  end
end

def chooseNumber(msgwindow, params)
  return 0 if !params

  ret = 0
  centered = msgwindow.nil?
  maximum = params.maxNumber
  minimum = params.minNumber
  defaultNumber = params.initialNumber
  cancelNumber = params.cancelNumber
  cmdwindow = Window_InputNumber.new(params.maxDigits)
  cmdwindow.x = Graphics.width / 2 - 68 if centered
  cmdwindow.y = Graphics.height / 2 - 36 if centered
  cmdwindow.z = 99999
  cmdwindow.visible = true
  cmdwindow.setSkin(params.skin) if params.skin && !centered
  cmdwindow.sign = params.negativesAllowed # must be set before number
  cmdwindow.number = defaultNumber
  curnumber = defaultNumber
  lastread = cmdwindow.number
  positionNearMsgWindow(cmdwindow, msgwindow, :right) unless centered
  command = 0
  loop do
    Graphics.update
    Input.update
    cmdwindow.update
    msgwindow.update unless centered
    if lastread != cmdwindow.number
      lastread = cmdwindow.number
    end
    yield if block_given?
    if Input.trigger?(Input::C)
      ret = params.autoClamp(cmdwindow.number)
      if ret > maximum

      elsif ret < minimum

      else
        # no audio
        break
      end
    elsif Input.trigger?(Input::B)

      ret = cancelNumber
      graphicsWait(2)
      break
    elsif Input.trigger?(Input::Y)
    end
  end
  cmdwindow.dispose
  Input.update
  return ret
end

def showCommandsWithHelp(msgwindow, commands, help, cmdIfCancel = 0, defaultCmd = 0, advanced: true)
  msgwin = msgwindow
  if !msgwindow
    msgwin = createMessageWindow(nil)
  end
  oldlbl = msgwin.letterbyletter
  msgwin.letterbyletter = false
  if commands
    cmdwindow = Window_AdvancedCommand.new(commands, defaultIndex: defaultCmd)
    $game_temp.cmd_window = cmdwindow if defined?(ZoomMap)
    cmdwindow.z = 99999
    cmdwindow.visible = true
    cmdwindow.resizeToFit(cmdwindow.commands)
    cmdwindow.height = msgwin.y if cmdwindow.height > msgwin.y
    command = 0
    msgwin.text = help[cmdwindow.index]
    msgwin.width = msgwin.width # Necessary evil to make it use the proper margins.
    loop do
      Graphics.update
      Input.update
      oldindex = cmdwindow.index
      cmdwindow.update
      if oldindex != cmdwindow.index
        msgwin.text = help[cmdwindow.index]
      end
      msgwin.update
      yield if block_given?
      if Input.trigger?(Input::B) && cmdIfCancel != 0 # cmdIfCancel being 0 makes it so you can't cancel out of the menu
        command = cmdIfCancel > 0 ? cmdIfCancel - 1 : cmdIfCancel
        graphicsWait(2)
        break
      end
      if Input.trigger?(Input::C)
        command = cmdwindow.index
        break
      end
      if Input.trigger?(Input::Y)
      end
    end
    ret = command
    cmdwindow.dispose
    Input.update
  end
  msgwin.letterbyletter = oldlbl
  if !msgwindow
    msgwin.dispose
  end
  return ret
end

