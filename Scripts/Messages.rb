def showCommands(msgwindow, commands = nil, cmdIfCancel = 0, defaultCmd = 0, advanced: true, delay: false)
  ret = 0
  if commands
    cmdwindow = Window_AdvancedCommand.new(commands, defaultIndex: defaultCmd, delay: delay)
    $game_temp.cmd_window = cmdwindow if defined?(ZoomMap)
    cmdwindow.z = 99999
    cmdwindow.visible = true
    cmdwindow.resizeToFit(cmdwindow.commands)
    positionNearMsgWindow(cmdwindow, msgwindow, :right)
    command = 0
    logtext = nil
    loop do
      Graphics.update
      Input.update
      oldindex = cmdwindow.index
      cmdwindow.update
      if oldindex != cmdwindow.index || Input.trigger?(Input::RIGHT) || Input.trigger?(Input::LEFT)
        if cmdwindow.delay
          cmdwindow.delay = false
          cmdwindow.index = defaultCmd
          command = 0
        end
      end
      msgwindow.update if msgwindow
      yield if block_given?
      if Input.trigger?(Input::B) && cmdwindow.delay == false && cmdIfCancel != 0 # cmdIfCancel being 0 makes it so you can't cancel out of the menu
        command = cmdIfCancel > 0 ? cmdIfCancel - 1 : cmdIfCancel
        logtext = cmdIfCancel > 0 ? commands[command] : _INTL("[Canceled]")
        graphicsWait(2)
        break
      end
      if Input.trigger?(Input::C) && cmdwindow.delay == false
        command = cmdwindow.index
        logtext = commands[command]
        break
      end
      if Input.trigger?(Input::Y)
      end
    end
    ret = command
    cmdwindow.dispose
    Input.update
  end
  return ret
end

def positionNearMsgWindow(cmdwindow, msgwindow, side)
  return if !cmdwindow

  if msgwindow
    height = [cmdwindow.height, Graphics.height - msgwindow.height].min
    if cmdwindow.height != height
      cmdwindow.height = height
    end
    cmdwindow.y = msgwindow.y - cmdwindow.height
    if cmdwindow.y < 0
      cmdwindow.y = msgwindow.y + msgwindow.height
      if cmdwindow.y + cmdwindow.height > Graphics.height
        cmdwindow.y = msgwindow.y - cmdwindow.height
      end
    end
    case side
      when :left
        cmdwindow.x = msgwindow.x
      when :right
        cmdwindow.x = msgwindow.x + msgwindow.width - cmdwindow.width
      else
        cmdwindow.x = msgwindow.x + msgwindow.width - cmdwindow.width
    end
  else
    cmdwindow.height = Graphics.height if cmdwindow.height > Graphics.height
    cmdwindow.x = 0
    cmdwindow.y = 0
  end
end

def showMessage(message, commands = nil, cmdIfCancel = 0, skin = nil, defaultCmd = 0, delay: false, advanced: true, &block)
  ret = 0
  msgwindow = createMessageWindow(nil, skin)
  if commands
    ret = messageDisplay(
      msgwindow, message, true,
      proc { |msgwindow|
        next showCommands(msgwindow, commands, cmdIfCancel, defaultCmd, delay: delay, &block)
      },
      log: log,
      &block
    )
  else
    messageDisplay(msgwindow, message, &block)
  end
  disposeMessageWindow(msgwindow)
  Input.update
  return ret
end

