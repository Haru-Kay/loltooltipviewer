  if event
    if eventChanged
      msgwindow.resizeToFit2(msgwindow.text, Graphics.width * 2 / 3, msgwindow.height)
    end
    msgwindow.y = event.screen_y - 48 - msgwindow.height
    if msgwindow.y < 0
      msgwindow.y = event.screen_y + 24
    end
    msgwindow.x = event.screen_x - (msgwindow.width / 2)
    msgwindow.x = 0 if msgwindow.x < 0
    if msgwindow.x > Graphics.width - msgwindow.width
      msgwindow.x = Graphics.width - msgwindow.width
    end
  else
    curwidth = msgwindow.width
    if curwidth != Graphics.width
      msgwindow.width = Graphics.width
      msgwindow.width = Graphics.width
    end
  end
end

def messageWaitForInput(msgwindow, frames, showPause = false)
  return if !frames || frames <= 0

  if msgwindow && showPause
    msgwindow.startPause
  end
  frames.times do
    Graphics.update
    Input.update
    msgwindow.update if msgwindow
    if Input.trigger?(Input::F5)
      return
    end
    if Input.trigger?(Input::C) || Input.trigger?(Input::B)
      break
    end
  end
  if msgwindow && showPause
    msgwindow.stopPause
  end
end

def messageDisplay(msgwindow, message, letterbyletter = true, commandProc = nil)
  return if !msgwindow

  oldletterbyletter = msgwindow.letterbyletter
  msgwindow.letterbyletter = (letterbyletter ? true : false)
  ret = nil
  count = 0
  commands = nil
  facewindow = nil
  goldwindow = nil
  coinwindow = nil
  apwindow = nil
  cmdvariable = 0
  cmdIfCancel = 0
  msgwindow.waitcount = 0
  autoresume = false
  text = message.clone
  msgback = nil
  linecount = Graphics.height > 400 ? 3 : 2
  isDarkSkin = isDarkWindowskin(msgwindow.windowskin)
  ### Text replacement

  # wskin control allows for separate color tags for light and dark
  # format:
  # \wskin[ifdark|iflight]
  # \wskin{ifdark|iflight}
  # allows for braces to enable other controls to be used within
  text.gsub!(/\\wskin\[([^|\]]*)\|([^|\]]*)\]/) { isDarkSkin ? $1 : $2 }
  text.gsub!(/\\wskin\{([^|}]*)\|([^|}]*)}/) { isDarkSkin ? $1 : $2 }

  text.gsub!(/\\\\/, "\5")
  if $game_actors
    text.gsub!(/\\n\[([1-8])\]/i) {
      m = $1.to_i
      next $game_actors[m].name
    }
  end
  text.gsub!(/\\sign\[([^\]]*)\]/i) {
    next "\\op\\cl\\ts[]\\w[" + $1 + "]"
  }
  text.gsub!(/\\[Pp][Nn]Upper/, $Trainer.name.upcase) if $Trainer
  text.gsub!(/\\[Pp][Nn]Lower/, $Trainer.name.downcase) if $Trainer
  text.gsub!(/\\pn/i, $Trainer.name) if $Trainer
  text.gsub!(/\\pm/i, _INTL("{1}", getPurchaseDisplay($Trainer.money))) if $Trainer
  text.gsub!(/\\n/i, "\n")
  text.gsub!(/\\\[([0-9A-Fa-f]{8,8})\]/) { "<c2=" + $1 + ">" }
  text.gsub!(/\\pg/i, "\\b") if $Trainer && $Trainer.isMale?
  text.gsub!(/\\pg/i, "\\r") if $Trainer && $Trainer.isFemale?
  text.gsub!(/\\pog/i, "\\r") if $Trainer && $Trainer.isMale?
  text.gsub!(/\\pog/i, "\\b") if $Trainer && $Trainer.isFemale?
  text.gsub!(/\\pg/i, "")
  text.gsub!(/\\pog/i, "")
  text.gsub!(/\\b/i, "<c2=6546675A>")
  text.gsub!(/\\r/i, "<c2=043C675A>")
  text.gsub!(/\\1/, TextPlaceholders::InputPause)
  colortag = ""

  colortag = getSkinColor(msgwindow.windowskin, 0, isDarkSkin)

  # \c[#]
  text.gsub!(/\\c\[([0-9]+)\]/i) {
    next getSkinColor(msgwindow.windowskin, $1.to_i, isDarkSkin)
  }
  # \c[l#] and \c[d#] support forcing colors from dark or light as needed
  # \c[l#]
  text.gsub!(/\\c\[l([0-9]+)\]/i) {
    next getSkinColor(msgwindow.windowskin, $1.to_i, false)
  }
  # \c[d#]
  text.gsub!(/\\c\[d([0-9]+)\]/i) {
    next getSkinColor(msgwindow.windowskin, $1.to_i, true)
  }

  begin
    last_text = text.clone
    text.gsub!(/\\l\[([0-9]+)\]/i) {
      linecount = [1, $1.to_i].max
      next ""
    }
  end until text == last_text
  text = colortag + text
  ### Controls
  textchunks = []
  controls = []
  while text[/(?:\\(w|f|ff|ffr|ts|st|cl|me|wt|wtnp|ch)\[([^\]]*)\]|\\(g|cn|ap|wd|wm|op|sh|cl|wu|\.|\||!|\^)())|<nolog>/i]
    textchunks.push($~.pre_match)
    if $~[1]
      if $~[1].downcase == "st"
        text = TextPlaceholders::ShakingTextStart + "#{$~[2]}" + TextPlaceholders::ShakingTextStop + $~.post_match
        next
      else
        controls.push([$~[1].downcase, $~[2], -1])
      end
    elsif $~[3]
      controls.push([$~[3].downcase, "", -1])
    else # <nolog>
      controls.push([$~[0], "", -1])
    end
    text = $~.post_match
  end
  textchunks.push(text)
  for chunk in textchunks
    chunk.gsub!(/\005/, "\\")
  end
  textlen = 0
  for i in 0...controls.length
    control = controls[i][0]
    if control == "wt" || control == "wtnp" || control == "." || control == "|"
      textchunks[i] += TextPlaceholders::TimedPause
    elsif control == "!"
      textchunks[i] += TextPlaceholders::InputPause
    end
    textlen += toUnformattedText(textchunks[i]).scan(/./m).length
    controls[i][2] = textlen
  end
  text = textchunks.join("")
  signWaitCount = 0
  shout = false
  haveSpecialClose = false
  for i in 0...controls.length
    control = controls[i][0]
    param = controls[i][1]
    if control == "f"
      facewindow.dispose if facewindow
      facewindow = PictureWindow.new("Graphics/Pictures/#{param}")
    elsif control == "op"
      signWaitCount = 21
    elsif control == "sh"
      shout = true
      signWaitCount = 16
      msgwindow.setSkin("Graphics/Windowskins/shout")
      msgwindow.width = msgwindow.width # Necessary evil
    elsif control == "cl"
      text = text.sub(/\001\z/, "") # fix: '$' can match end of line as well
      haveSpecialClose = true
    elsif control == "ff"
      facewindow.dispose if facewindow
      facewindow = FaceWindowVX.new(param)
    elsif control == "ch"
      cmds = param.clone
      cmdvariable = csvPosInt!(cmds)
      cmdIfCancel = csvField!(cmds).to_i
      commands = []
      while cmds.length > 0
        commands.push(csvField!(cmds))
      end
    elsif control == "wtnp" || control == "^"
      text = text.sub(/\001\z/, "") # fix: '$' can match end of line as well
    end
  end
  ########## Position message window  ##############
  repositionMessageWindow(msgwindow, linecount)
  if $game_message && $game_message.background == 1
    msgback = IconSprite.new(0, msgwindow.y, msgwindow.viewport)
    msgback.z = msgwindow.z - 1
    msgback.setBitmap("Graphics/System/MessageBack")
  end
  if facewindow
    positionNearMsgWindow(facewindow, msgwindow, :left)
    facewindow.viewport = msgwindow.viewport
    facewindow.z = msgwindow.z
  end
  atTop = msgwindow.y == 0
  ########## Show text #############################
  msgwindow.text = text
  # Add message to text log, if message comes from command_101 (ie, from RMXP data) and doesn't have '<nolog>' tag
  Graphics.frame_reset if Graphics.frame_rate > 40
  begin
    if signWaitCount != 0 && shout
      signWaitCount = (signWaitCount * -0.9).floor
      if atTop
        msgwindow.y = signWaitCount
      else
        msgwindow.y = Graphics.height - (msgwindow.height + signWaitCount)
      end
    elsif signWaitCount > 0
      signWaitCount -= 1
      if atTop
        msgwindow.y = -(msgwindow.height * signWaitCount / 20)
      else
        msgwindow.y = Graphics.height - (msgwindow.height * (20 - signWaitCount) / 20)
      end
    end
    for i in 0...controls.length
      if controls[i] && controls[i][2] <= msgwindow.position && msgwindow.waitcount == 0
        control = controls[i][0]
        param = controls[i][1]
        if control == "f"
          facewindow.dispose if facewindow
          facewindow = PictureWindow.new("Graphics/Pictures/#{param}")
          positionNearMsgWindow(facewindow, msgwindow, :left)
          facewindow.viewport = msgwindow.viewport
          facewindow.z = msgwindow.z
        elsif control == "ts"
          if param == ""
            msgwindow.textspeed = -999
          else
            msgwindow.textspeed = param.to_i
          end
        elsif control == "ff"
          facewindow.dispose if facewindow
          facewindow = FaceWindowVX.new(param)
          positionNearMsgWindow(facewindow, msgwindow, :left)
          facewindow.viewport = msgwindow.viewport
          facewindow.z = msgwindow.z
        elsif control == "ffr"
          facewindow.dispose if facewindow
          facewindow = FaceWindowVX.new(param)
          positionNearMsgWindow(facewindow, msgwindow, :right)
          facewindow.viewport = msgwindow.viewport
          facewindow.z = msgwindow.z
        elsif control == "wu"
          msgwindow.y = 0
          atTop = true
          msgback.y = msgwindow.y if msgback
          positionNearMsgWindow(facewindow, msgwindow, :left)
          msgwindow.y = -(msgwindow.height * signWaitCount / 20)
        elsif control == "wm"
          atTop = false
          msgwindow.y = (Graphics.height / 2) - (msgwindow.height / 2)
          msgback.y = msgwindow.y if msgback
          positionNearMsgWindow(facewindow, msgwindow, :left)
        elsif control == "wd"
          atTop = false
          msgwindow.y = Graphics.height - msgwindow.height
          msgback.y = msgwindow.y if msgback
          positionNearMsgWindow(facewindow, msgwindow, :left)
          msgwindow.y = Graphics.height - (msgwindow.height * (20 - signWaitCount) / 20)
        elsif control == "."
          msgwindow.waitcount += Graphics.frame_rate / 4
        elsif control == "|"
          msgwindow.waitcount += Graphics.frame_rate
        elsif control == "wt" # Wait
          param = param.sub(/\A\s+/, "").sub(/\s+\z/, "")
          msgwindow.waitcount += param.to_i * 2
        elsif control == "w" # Windowskin
          if param == ""
            msgwindow.windowskin = nil
          else
            msgwindow.setSkin("Graphics/Windowskins/#{param}")
          end
          msgwindow.width = msgwindow.width # Necessary evil
        elsif control == "^" # Wait, no pause
          autoresume = true
        elsif control == "wtnp" # Wait, no pause
          param = param.sub(/\A\s+/, "").sub(/\s+\z/, "")
          msgwindow.waitcount = param.to_i * 2
          autoresume = true
        elsif control == "se" # Play SE

        elsif control == "me" # Play ME

        end
        controls[i] = nil
      end
    end
    break if !letterbyletter

    Graphics.update
    Input.update
    facewindow.update if facewindow
    if autoresume && msgwindow.waitcount == 0
      msgwindow.resume if msgwindow.busy?
      break if !msgwindow.busy?
    end
    if $Settings.textskipwait == 1 ? Input.press?(Input::B) : Input.time?(Input::B) > 0.15
      msgwindow.textspeed = -999
      msgwindow.update
      if msgwindow.busy?
        # no audio
        msgwindow.resume
      else
        break if signWaitCount == 0
      end
    end
    if Input.trigger?(Input::C)
      if msgwindow.busy? && (!$game_switches || !$game_switches[:Blindstep])
        # no audio
        msgwindow.resume
      else
        break if signWaitCount == 0
      end
    end
    if Input.trigger?(Input::Y)
    end
    msgwindow.update
    yield if block_given?
  end until (!letterbyletter || commandProc || commands) && !msgwindow.busy?
  Input.update # Must call Input.update again to avoid extra triggers
  msgwindow.letterbyletter = oldletterbyletter
  if commands
    $game_variables[cmdvariable] = showCommands(msgwindow, commands, cmdIfCancel)
    $game_map.need_refresh = true if $game_map
  end
  if commandProc
    ret = commandProc.call(msgwindow)
  end
  msgback.dispose if msgback
  goldwindow.dispose if goldwindow
  coinwindow.dispose if coinwindow
  apwindow.dispose if apwindow
  facewindow.dispose if facewindow
  if haveSpecialClose
    atTop = msgwindow.y == 0
    for i in 0..20
      if atTop
        msgwindow.y = -(msgwindow.height * (i) / 20)
      else
        msgwindow.y = Graphics.height - (msgwindow.height * (20 - i) / 20)
      end
      Graphics.update
      Input.update
      msgwindow.update
    end
  end
  return ret
end

FORMATREGEXP = /<(\/?)([Cc]|[Cc][2]|[Cc][33]|[Gg][Rr]|[Ll][Hh]|[Oo]|[Ff][Nn]|[Bb][Rr]|[Ll][Ii]|[Ff][Ss]|[Ii]|[Bb]|[Rr]|[Pp][Gg]|[Pp][Oo][Gg]|[Uu]|[Ss]|[Ii][Cc][Oo][Nn]|[Ii][Mm][Gg]|[Aa][Cc]|[Aa][Rr]|[Aa][Ll]|[Oo][Uu][Tt][Ll][Nn]|[Oo][Uu][Tt][Ll][Nn][2])(\s*\=\s*([^>]*))?>/

def toUnformattedText(text)
  text = text.dup
  text.gsub!(FORMATREGEXP, "")
  text.gsub!(/&lt;/, "<")
  text.gsub!(/&gt;/, ">")
  text.gsub!(/&apos;/, "'")
  text.gsub!(/&quot;/, "\"")
  text.gsub!(/&amp;/, "&")
  text.gsub!(/<(\/?)(font|font color)(\s*\=\s*([^>]*))?>/, "")
  text.gsub!(/<(\/?)(lol-uikit-tooltipped-keyword)( key|)(\s*\=\s*([^>]*))?>/, "")
  while text[/%(i)(:([^>].*?))%/]
    m = $~.dup
    icon = m[3].downcase
    icon.gsub!("scale", "")
    icon.gsub!("active", "")
    icon.gsub!("mini", "")
    icon = "" unless [
      "augment", "cooldown", "coins", "melee", "adaptiveforce", "onhit", "ranged", "ad", "ap", "apen",
      "armor", "as", "crit", "critmult", "healshield", "health", "hpregen", "level", "ls", "mana",
      "manaregen", "mpen", "mr", "ms", "range", "size", "sv", "tenacity", "statanvil"
    ].include?(icon)
    text = (m.pre_match + " #{icon} " + m.post_match).gsub("  ", " ")
  end
  return text
end

def unformattedTextLength(text)
  return toUnformattedText(text).scan(/./m).length
end
